// The companion's entry disclosure (handoff 09 §11).
//
// §11 lists AI companion placement as an open decision, and its objection is
// structural rather than cosmetic: "The companion does not appear in the Vol 2
// session state machine at all. It needs a defined position relative to the
// routing engine before it gets a position on screen." Until that position
// exists, it attaches one interim condition:
//
//   "Until then, ENTRY STATES IT IS AI and NAMES ITS COMMUNICATION LIMITS."
//
// DECIDED 2026-09-09: keep the companion where it is, and meet that condition
// properly. It was not met. The companion carried one line — "Your companion is
// supportive software, not a therapist or emergency care" — and it sat BELOW
// the message thread, after the conversation, where it is read (if at all) by
// somebody who has already used the thing. §11 says ENTRY.
//
// AND "SUPPORTIVE SOFTWARE" IS NOT "AI". A spreadsheet is supportive software.
// The condition is specific because the thing a person needs to know before
// typing something private is not that a program is involved — it is that the
// replies are generated, and that no person is reading them.
//
// THE LIMITS ARE NAMED, not gestured at. §11 says "names its communication
// limits", which is a different requirement from a disclaimer: a disclaimer
// protects the product, and this is supposed to tell somebody what will and
// will not happen when they type. So each entry below is a thing the companion
// cannot do, said plainly, and the set is deliberately short enough to be read.
//
// NO IMPORTS. Rendered by a client component; a disclosure that drags a
// database driver into the browser bundle is its own defect.

