/**
 * Whether the disclosure has been placed where §11 requires.
 *
 * A predicate rather than a comment, because "at entry" is the part that
 * silently stops being true: a later edit that moves this below the thread, or
 * renders it only after the first message, leaves every word intact and undoes
 * the condition entirely. `beforeFirstExchange` is what the guard checks.
 */
export function meetsEntryCondition(placement: {
  beforeFirstExchange: boolean;
  statesItIsAi: boolean;
  namesLimits: number;
}): boolean {
  return (
    placement.beforeFirstExchange &&
    placement.statesItIsAi &&
    placement.namesLimits >= COMPANION_LIMITS.length
  );
}

/**
 * The one thing §11 actually asserts about position, held as a rule.
 *
 * The companion has no place in the Vol 2 session state machine. That is not a
 * gap to fill by choosing a place — choosing one is the founder decision §11
 * reserves — but it does license a negative: whatever position it eventually
 * gets, it is not a step inside a session, because the state machine that
 * defines those steps does not contain it.
 */
export const COMPANION_IS_NOT_A_SESSION_STEP = true;
